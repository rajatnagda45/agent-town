// Transpiles the vendored, unmodified Meterless H-MEM reference engine (TypeScript) to plain
// JavaScript in lib/vendor/hmem-reference/dist, so the packaged server runs it on plain Node.
// Only types are removed and relative ".ts" imports become ".mjs"; behaviour is unchanged, and
// `pnpm hmem:conformance` runs the official suite against this built output.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import ts from "typescript";

const source = resolve("lib/vendor/hmem-reference");
const out = join(source, "dist");
mkdirSync(out, { recursive: true });
for (const file of readdirSync(source).filter((name) => name.endsWith(".ts"))) {
  const { outputText } = ts.transpileModule(readFileSync(join(source, file), "utf8"), {
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2022,
      verbatimModuleSyntax: false,
    },
    fileName: file,
  });
  const code = outputText.replace(/(from\s+["']\.\/[^"']+)\.ts(["'])/g, "$1.mjs$2");
  writeFileSync(
    join(out, file.replace(/\.ts$/, ".mjs")),
    `// Generated by scripts/build-hmem.mjs from ../${file} (Apache-2.0, Meterless). Do not edit.\n${code}`,
  );
}
console.log(`Built H-MEM engine → ${out}`);
